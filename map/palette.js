/* ===== 風の芽経済組：国土の地図の色 =====
   地形（t）・標高（e）・用途地域（z）からマスの色を決める。遠くから見る画像（overview.png）と、画面の地図（map.js）で同じ色 */
(function (root) {
'use strict';
// 地形：D 深い海・S 海・R 川・L 湖・B 砂浜・P 平地・F 林・H 丘・M 山・K 高い山
const TC = { D: [70, 128, 186], S: [112, 170, 220], R: [96, 162, 224], L: [100, 166, 226], B: [236, 228, 190],
             P: [214, 231, 186], F: [170, 205, 142], H: [196, 206, 158], M: [166, 176, 132], K: [196, 188, 170] };
// 用途地域で、まちの色をのせる（地図らしく：住宅地はうすい灰色、商業地はもう少し濃く、工業地は青っぽい灰色、公園は緑）
const ZT = { a: [[232, 228, 218], 0.55], b: [[226, 220, 210], 0.65], c: [[218, 210, 202], 0.75], d: [[208, 200, 194], 0.85],
             e: [[218, 218, 224], 0.6], f: [[210, 214, 226], 0.7], g: [[204, 210, 224], 0.75], j: [[178, 218, 152], 0.6], h: [[224, 233, 192], 0.35],
             k: [[222, 223, 214], 0.45] };   // k：住居・港湾（島）
// 用途地域の層（法律の色に近い・はっきり）
const ZC = { a: [60, 179, 113], b: [240, 230, 140], c: [255, 182, 193], d: [255, 99, 99], e: [200, 162, 200], f: [135, 206, 235], g: [74, 163, 199], h: [217, 194, 122], i: [107, 142, 78], j: [154, 205, 50], k: [255, 150, 50] };
const ZN = { a: '低層住居', b: '住居', c: '近隣商業', d: '商業', e: '準工業', f: '工業', g: '港湾', h: '農業', i: '森林', j: '公園', k: '住居・港湾' };
const isWater = t => t === 'D' || t === 'S' || t === 'R' || t === 'L';
// マスの色（slope：北西からの下り具合 m/マス。かげをつける）
function tileColor(t, e, z, slope) {
  const b = TC[t] || TC.P;
  if (isWater(t)) return b.slice();
  let c = b.slice();
  if (t !== 'B' && e > 150) { const f = Math.min(1, (e - 150) / 1500) * 0.5; c = [c[0] * (1 - f) + 186 * f, c[1] * (1 - f) + 172 * f, c[2] * (1 - f) + 140 * f]; }
  const zt = ZT[z];
  if (zt && t !== 'B') { const f = t === 'F' ? zt[1] * 0.5 : zt[1]; c = [c[0] * (1 - f) + zt[0][0] * f, c[1] * (1 - f) + zt[0][1] * f, c[2] * (1 - f) + zt[0][2] * f]; }
  const sh = 1 + Math.max(-0.28, Math.min(0.28, -(slope || 0) * 0.02));
  return [Math.min(255, c[0] * sh), Math.min(255, c[1] * sh), Math.min(255, c[2] * sh)];
}
const MapPal = { TC, ZT, ZC, ZN, isWater, tileColor };
if (typeof module !== 'undefined' && module.exports) module.exports = MapPal; else root.MapPal = MapPal;
})(typeof self !== 'undefined' ? self : this);
