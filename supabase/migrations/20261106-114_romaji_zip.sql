    elsif zr ~ 'u$' and zx = 'う' then zr := left(zr, -1) || 'ū'; zi := zi + 1;
    end if;
    zo := zo || zr;
  end loop;
  return zo;
end $$;
-- はじめの1文字を大文字に（ō → Ō も）
create or replace function public._mp_ro_cap(s text) returns text
language sql immutable as $$
  select case when coalesce(s, '') = '' then s else translate(upper(left(s, 1)), 'āīūēō', 'ĀĪŪĒŌ') || substr(s, 2) end
$$;
-- 種類（市・区・町・村・県・府・郡）のローマ字。ty：読みの指定（ひらがな。町を ちょう・村を そん と読むとき）
create or replace function public._mp_type_ro(t text, ty text) returns text
language sql immutable as $$
  select case when coalesce(ty, '') <> '' then _mp_kana_ro(ty)
              else case t when '市' then 'shi' when '区' then 'ku' when '町' then 'machi' when '村' then 'mura' when '県' then 'ken'
                          when '府' then 'fu' when '都' then 'to' when '郡' then 'gun' else '' end end
$$;
-- 地名のローマ字（例：Tsukimi-shi）。y：読み（「つきみ」・種類の読みもつけるときは「すずの ちょう」）、t：種類
create or replace function public._mp_ro_name(y text, t text) returns text
language sql immutable as $$
  select case when coalesce(btrim(y), '') = '' then null
    else _mp_ro_cap(_mp_kana_ro(split_part(btrim(y), ' ', 1))) || coalesce('-' || nullif(_mp_type_ro(t, nullif(split_part(btrim(y), ' ', 2), '')), ''), '') end
$$;
-- ローマ字をさがすときのキー（ヘボン式・訓令式・のばす音の書きかたの ちがいを そろえる）
create or replace function public._mp_rokey(s text) returns text
language plpgsql immutable as $$
declare zk text := lower(translate(coalesce(s, ''), 'ĀĪŪĒŌāīūēōÂÎÛÊÔâîûêôÁÍÚÉÓáíúéó', 'AIUEOaiueoAIUEOaiueoAIUEOaiueo'));
begin
  zk := regexp_replace(zk, '[^a-z]', '', 'g');
  zk := replace(zk, 'chi', 'ti'); zk := replace(zk, 'tch', 'tty');
  zk := replace(zk, 'sh', 'sy'); zk := replace(zk, 'ch', 'ty'); zk := replace(zk, 'tsu', 'tu');
  zk := replace(zk, 'syi', 'si'); zk := replace(zk, 'tyi', 'ti');
  zk := replace(zk, 'fu', 'hu'); zk := replace(zk, 'ji', 'zi'); zk := replace(zk, 'j', 'zy'); zk := replace(zk, 'zyi', 'zi');
  zk := replace(zk, 'dzu', 'zu'); zk := replace(zk, 'du', 'zu'); zk := replace(zk, 'di', 'zi');
  zk := regexp_replace(zk, 'm([bpm])', 'n\1', 'g');
  zk := regexp_replace(zk, 'o[ouh](?![aiueoy])', 'o', 'g');
  zk := replace(zk, 'uu', 'u');
  return zk;
end $$;
-- 区域（市町村・区・県）の ローマ字（例：Nakazato-ku, Ruri-shi, Ruri-fu・Suzuno-machi, Kawa-gun, Kohaku-ken）。読みのないものがあれば null
create or replace function public._mp_area_ro(aid text) returns text
language sql stable set search_path = public as $$
  select case when ar.k = 'pref' then ar.ro
              when pr.ro is not null and mu.ro is not null and (ar.k <> 'ward' or ar.ro is not null) then
                concat_ws(', ', case when ar.k = 'ward' then ar.ro end, mu.ro,
                          case when mu.type in ('町', '村') and coalesce(mu.extra ->> 'gun', '') <> '' then _mp_ro_name(mu.extra ->> 'gyomi', '郡') end, pr.ro) end
    from mp_places ar left join mp_places mu on mu.id = case when ar.k = 'ward' then ar.parent else ar.id end left join mp_places pr on pr.id = mu.parent
   where ar.id = aid
$$;
-- 町字の郵便番号（丁目・字は その町・大字の番号）
create or replace function public._mp_cho_zip(cid text) returns text
language sql stable set search_path = public as $$
  select case when c.kind in ('chome', 'aza') then (select p.zip from mp_cho p where p.id = c.parent) else c.zip end from mp_cho c where c.id = cid
$$;
-- 地名の 読み → ローマ字・さがすキー
create or replace function public._mp_places_ro_trg() returns trigger
language plpgsql set search_path = public as $$
begin
  new.ro := _mp_ro_name(new.yomi, new.type);
  new.rk := case when new.ro is not null then _mp_rokey(_mp_kana_ro(split_part(btrim(new.yomi), ' ', 1))) end;
  new.rkf := case when new.ro is not null then _mp_rokey(new.ro) end;
  return new;
end $$;
drop trigger if exists mp_places_ro on public.mp_places;
create trigger mp_places_ro before insert or update of yomi, type on public.mp_places for each row execute function public._mp_places_ro_trg();
-- 新しい町・大字の郵便番号：その区域の つぎの番号
create or replace function public._mp_cho_zip_trg() returns trigger
language plpgsql set search_path = public as $$
declare zz text; zn int;
begin
  if new.kind in ('cho', 'oaza') and new.zip is null then
    select zip into zz from mp_places where id = new.parent;
    if zz is not null then
      select coalesce(max(right(zip, 3)::int), 0) + 1 into zn from mp_cho where parent = new.parent and zip like left(zz, 4) || '%';
      if zn <= 999 then new.zip := left(zz, 4) || lpad(zn::text, 3, '0'); end if;
    end if;
  end if;
  return new;
end $$;
drop trigger if exists mp_cho_zip on public.mp_cho;
create trigger mp_cho_zip before insert on public.mp_cho for each row execute function public._mp_cho_zip_trg();
-- 郵便番号を決める（まだのものだけ）：県 → 区域 → 町・大字
create or replace function public._mp_zip_assign() returns jsonb
language plpgsql set search_path = public as $$
declare zp int := 0; za int := 0; zc int := 0;
begin
  -- 県：はじめの3けた（瑠璃府 100・ほかの県は 瑠璃から近い順に 30 ずつ）
  with zb as (select coalesce(max(zip::int), 70) b from mp_places where k = 'pref' and zip ~ '^[0-9]{3}$'),
       zq as (select id, row_number() over (order by (id = 'p:ruri') desc, x::numeric * x + y::numeric * y, id) n from mp_places where k = 'pref' and zip is null)
  update mp_places p set zip = (zb.b + 30 * zq.n)::text from zq, zb where p.id = zq.id and zb.b + 30 * zq.n <= 970;
  get diagnostics zp = row_count;
  -- 区域（区のない市町村・区）：県の中で、県の中心から近い順に 4けため（10ずつで つぎの3けた）。県が見つからない区域は いちばん近い県
  with zall0 as (select a.id, a.zip, a.x, a.y, case when a.k = 'ward' then m.parent else a.parent end pid
                   from mp_places a left join mp_places m on a.k = 'ward' and m.id = a.parent
                  where a.k = 'ward' or (a.k = 'muni' and not exists (select 1 from mp_places w where w.k = 'ward' and w.parent = a.id))),
       zall as (select z.id, z.zip, z.x, z.y, coalesce((select pr.id from mp_places pr where pr.id = z.pid and pr.k = 'pref'),
                                                      (select pr.id from mp_places pr where pr.k = 'pref' order by pr.pt <-> point(z.x, z.y) limit 1)) pid from zall0 z),
       zu as (select z.pid, max((left(z.zip, 3)::int - pr.zip::int) * 10 + substr(z.zip, 4, 1)::int) + 1 nx
                from zall z join mp_places pr on pr.id = z.pid and pr.zip ~ '^[0-9]{3}$' where z.zip is not null group by z.pid),
       zq as (select z.id, pr.zip::int blk, coalesce(zu.nx, 0) + row_number() over (partition by z.pid order by (z.x - pr.x)::numeric * (z.x - pr.x) + (z.y - pr.y)::numeric * (z.y - pr.y), z.id) - 1 n
                from zall z join mp_places pr on pr.id = z.pid and pr.zip ~ '^[0-9]{3}$' left join zu on zu.pid = z.pid where z.zip is null)
  update mp_places p set zip = lpad((zq.blk + zq.n / 10)::text, 3, '0') || (zq.n % 10)::text || '000' from zq where p.id = zq.id and zq.n < 300;
  get diagnostics za = row_count;
  -- 町・大字：区域の中で、区域の中心から近い順に うしろの3けた（001〜999）
  with zu as (select c.parent, max(right(c.zip, 3)::int) mx from mp_cho c where c.zip is not null and c.kind in ('cho', 'oaza') group by c.parent),
       zq as (select c.id, a.zip az, coalesce(zu.mx, 0) + row_number() over (partition by c.parent order by (c.x - a.x)::numeric * (c.x - a.x) + (c.y - a.y)::numeric * (c.y - a.y), c.id) n
                from mp_cho c join mp_places a on a.id = c.parent and a.zip ~ '^[0-9]{7}$' left join zu on zu.parent = c.parent
               where c.kind in ('cho', 'oaza') and c.gone is null and c.zip is null)
  update mp_cho c set zip = left(zq.az, 4) || lpad(zq.n::text, 3, '0') from zq where c.id = zq.id and zq.n <= 999;
  get diagnostics zc = row_count;
  return jsonb_build_object('pref', zp, 'area', za, 'cho', zc);
end $$;

