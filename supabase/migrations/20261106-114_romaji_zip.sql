create or replace function public._mp_addr(px int, py int, cx int, cy int) returns jsonb
language plpgsql stable set search_path = public as $$
declare c record; ar mp_places; mu mp_places; pr mp_places; head text; ck text; ct text; pa mp_parcels; gun text;
begin
  select * into c from _mp_cell(px, py);
  if c.t is null then return jsonb_build_object('text', '（まだ地図がありません）'); end if;
  select * into ar from mp_places where id = c.a;
  if ar.k = 'ward' then select * into mu from mp_places where id = ar.parent; else mu := ar; end if;
  select * into pr from mp_places where id = mu.parent;
  if c.t in ('S', 'D') then
    return jsonb_build_object('text', coalesce(mu.name || mu.type, '') || 'の沖（海）', 'pref', pr.name || coalesce(nullif(pr.type, ''), '県'), 'muni', mu.name || mu.type);
  end if;
  gun := case when mu.type in ('町', '村') and coalesce(mu.extra ->> 'gun', '') <> '' then (mu.extra ->> 'gun') || '郡' else '' end;
  head := coalesce(pr.name || coalesce(nullif(pr.type, ''), '県'), '') || gun || coalesce(mu.name || mu.type, '') || case when ar.k = 'ward' then ar.name || '区' else '' end;
  if c.t in ('R', 'L') then
    return jsonb_build_object('text', head || '（' || case when c.t = 'R' then coalesce((select p.name from mp_places p where p.k = 'river' order by p.pt <-> point(px, py) limit 1), '川') else '湖' end || '）',
      'pref', pr.name || coalesce(nullif(pr.type, ''), '県'), 'muni', mu.name || mu.type, 'ward', case when ar.k = 'ward' then ar.name || '区' end);
  end if;
  ck := _mp_cho_at(px, py);
  ct := _mp_cho_text(ck, mu.type);
  if cx is not null then
    select p.* into pa from mp_pcells pc join mp_parcels p on p.id = pc.parcel where pc.x = cx and pc.y = cy;
    if found then ck := pa.cho; ct := _mp_cho_text(pa.cho, mu.type); end if;
  end if;
  return jsonb_build_object('text', head || ct, 'ban', case when pa.id is not null then _mp_ban(pa.ban, pa.eda) end,
    'pref', pr.name || coalesce(nullif(pr.type, ''), '県'), 'gun', nullif(gun, ''), 'muni', mu.name || mu.type, 'ward', case when ar.k = 'ward' then ar.name || '区' end, 'cho', ck, 'chot', ct,
    'zip', _mp_cho_zip(ck), 'ro', _mp_area_ro(ar.id));   -- 郵便番号・ローマ字（DB の更新114）
end $$;

create or replace function public.mp_find(p_q text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := _me_g(); q text := _mp_qnorm(p_q); rest text; pl record; sc text[] := '{}'; out jsonb := '[]'::jsonb; seen text[] := '{}';
        m text[]; base text; ban_ int; eda_ int; tries jsonb := '[]'::jsonb; t jsonb; r record; cids text[]; it int; zd text; zt text; zk text;
begin
  perform _mp_ok(u);
  if char_length(q) < 1 then return out; end if;
  -- 0) 郵便番号（〒100-0001・1000001。はじめの3〜6けたでも）（DB の更新114）
  if q ~ '^〒?[0-9]{3}-?[0-9]{0,4}$' then
    zd := regexp_replace(q, '[^0-9]', '', 'g');
    for r in select a.id, a.k, a.name, a.type, a.x, a.y, a.parent, a.ro, a.zip from mp_places a
              where a.k in ('muni', 'ward') and a.zip is not null
                and case when char_length(zd) <= 4 then a.zip like zd || '%' else a.zip = left(zd, 4) || '000' and (char_length(zd) < 7 or right(zd, 3) = '000') end
              order by a.zip limit 20 loop
      out := out || jsonb_build_array(jsonb_build_object('k', r.k, 'n', r.name || coalesce(r.type, ''), 's', coalesce(_mp_area_text(r.parent), ''), 'x', r.x + 0.5, 'y', r.y + 0.5,
        'z', case r.k when 'muni' then 2.2 else 4 end, 'ro', r.ro, 'zip', r.zip, 'sro', _mp_area_ro(r.parent)));
    end loop;
    if char_length(zd) >= 4 then
      for r in select c.id, c.x, c.y, c.zip from mp_cho c where c.zip like zd || '%' and c.gone is null order by c.zip limit 30 loop
        out := out || jsonb_build_array(jsonb_build_object('k', 'cho', 'n', _mp_cho_full(r.id), 's', _mp_cho_place(r.id, r.x, r.y), 'x', r.x + 0.5, 'y', r.y + 0.5, 'z', 12,
          'zip', r.zip, 'sro', _mp_area_ro(_mp_cho_area(r.id))));
      end loop;
    end if;
    return out;
  end if;
  -- 0b) ローマ字（Tsukimi・Tsukimi-shi・Nakazato-ku, Ruri-shi など。はじめの語で 都道府県・市区町村・区を さがす）（DB の更新114）
  zt := split_part(btrim(regexp_replace(normalize(coalesce(p_q, ''), NFKC), '[\s,、，]+', ' ', 'g')), ' ', 1);
  if zt ~ '^[A-Za-zĀĪŪĒŌāīūēōÂÎÛÊÔâîûêô''’.-]{2,40}$' then
    zk := _mp_rokey(regexp_replace(lower(zt), '-?(city|ward|town|village|prefecture|pref|county|district)$', ''));
    if char_length(zk) >= 2 then
      for r in select p.id, p.k, p.name, p.type, p.x, p.y, p.parent, p.ro, p.zip from mp_places p
                where p.k in ('pref', 'muni', 'ward') and (p.rk like zk || '%' or p.rkf like zk || '%')
                order by (p.rk = zk or p.rkf = zk) desc, p.pop desc nulls last, p.id limit 12 loop
        seen := seen || r.id;
        out := out || jsonb_build_array(jsonb_build_object('k', r.k, 'n', r.name || coalesce(r.type, ''), 's', coalesce(_mp_area_text(r.parent), ''), 'x', r.x + 0.5, 'y', r.y + 0.5,
          'z', case r.k when 'pref' then 0.7 when 'muni' then 2.2 else 4 end, 'ro', r.ro, 'zip', r.zip, 'sro', _mp_area_ro(r.parent)));
      end loop;
    end if;
  end if;
  -- 1) 前の地名（都道府県・郡・市区町村・区）をとる → その中でさがす
  rest := q;
  for it in 1..4 loop
    select p.id, p.k, p.name, p.type, p.x, p.y, p.pop, p.name || coalesce(case when p.k = 'pref' then nullif(p.type, '') else p.type end, '') full_ into pl
      from mp_places p
     where p.k in ('pref', 'muni', 'ward') and rest like (p.name || coalesce(case when p.k = 'pref' then nullif(p.type, '') else p.type end, '')) || '%'
       and (cardinality(sc) = 0 or p.parent = sc[cardinality(sc)] or p.k = 'pref')
     order by char_length(p.name || coalesce(p.type, '')) desc, p.pop desc nulls last limit 1;
    exit when not found or char_length(pl.full_) = 0;
    sc := sc || pl.id; rest := substr(rest, char_length(pl.full_) + 1);
    if pl.k = 'muni' and rest ~ '^[^市区町村郡]{1,6}郡' then rest := regexp_replace(rest, '^[^市区町村郡]{1,6}郡', ''); end if;
    if rest ~ '^[^市区町村郡]{1,6}郡' and pl.k = 'pref' then rest := regexp_replace(rest, '^[^市区町村郡]{1,6}郡', ''); end if;
    exit when rest = '';
  end loop;
  if cardinality(sc) > 0 and rest = '' then
    select * into pl from mp_places where id = sc[cardinality(sc)];
    out := out || jsonb_build_array(jsonb_build_object('k', pl.k, 'n', pl.name || coalesce(pl.type, ''), 's', coalesce(_mp_area_text(pl.parent), ''),
      'x', pl.x + 0.5, 'y', pl.y + 0.5, 'z', case pl.k when 'pref' then 0.7 when 'muni' then 2.2 else 4 end, 'ro', pl.ro, 'zip', pl.zip, 'sro', _mp_area_ro(pl.parent)));
    seen := seen || pl.id;
  end if;
  -- 2) 住所（町字＋地番）
  if rest <> '' then
    m := regexp_match(rest, '^(.*\D)(\d+)-(\d+)-(\d+)$');
    if m is not null then tries := tries || jsonb_build_array(jsonb_build_array(m[1] || _mp_kanji_num(m[2]::int) || '丁目', m[3]::int, m[4]::int)); end if;
    m := regexp_match(rest, '^(.*\D)(\d+)番地?の?(\d+)?号?$');
    if m is not null then tries := tries || jsonb_build_array(jsonb_build_array(m[1], m[2]::int, coalesce(m[3]::int, 0))); end if;
    m := regexp_match(rest, '^(.*\D)(\d+)-(\d+)$');
    if m is not null then
      tries := tries || jsonb_build_array(jsonb_build_array(m[1] || _mp_kanji_num(m[2]::int) || '丁目', m[3]::int, 0), jsonb_build_array(m[1], m[2]::int, m[3]::int));
    end if;
    m := regexp_match(rest, '^(.*\D)(\d+)$');
    if m is not null and m[1] ~ '(丁目|字.+|町|大字.+)$' then tries := tries || jsonb_build_array(jsonb_build_array(m[1], m[2]::int, 0)); end if;
    for t in select * from jsonb_array_elements(tries) loop
      base := t ->> 0; ban_ := (t ->> 1)::int; eda_ := (t ->> 2)::int;
      -- base の終わりにあう町字（いちばん細かいもの）
      if base ~ '[一二三四五六七八九十]+丁目$' then
        cids := array(select c.id from mp_cho c join mp_cho p on p.id = c.parent
                       where c.kind = 'chome' and c.gone is null and c.name = substring(base from '([一二三四五六七八九十]+丁目)$')
                         and (left(base, char_length(base) - char_length(c.name)) = p.name or left(base, char_length(base) - char_length(c.name)) like '%' || p.name)
                         and (cardinality(sc) = 0 or _mp_cho_area(c.id) = sc[cardinality(sc)] or (select a.parent from mp_places a where a.id = _mp_cho_area(c.id)) = sc[cardinality(sc)])
                       limit 20);
      elsif base ~ '字' then
        cids := array(select c.id from mp_cho c join mp_cho p on p.id = c.parent
                       where c.kind = 'aza' and c.gone is null and base like '%' || p.name || '字' || c.name
                         and (cardinality(sc) = 0 or _mp_cho_area(c.id) = sc[cardinality(sc)] or (select a.parent from mp_places a where a.id = _mp_cho_area(c.id)) = sc[cardinality(sc)])
                       limit 20);
      else
        cids := array(select c.id from mp_cho c
                       where c.kind in ('cho', 'oaza') and c.gone is null and (base = c.name or base like '%' || c.name) and char_length(c.name) >= 2
                         and not exists (select 1 from mp_cho k where k.parent = c.id and k.gone is null)
                         and (cardinality(sc) = 0 or c.parent = sc[cardinality(sc)] or (select a.parent from mp_places a where a.id = c.parent) = sc[cardinality(sc)])
                       limit 20);
      end if;
      for r in select p.id, p.cho, p.ban, p.eda, p.bb, (select b.id from mp_blds b where b.parcel = p.id) bid, (select b.name from mp_blds b where b.parcel = p.id) bname,
                      (select array[pc.x, pc.y] from mp_pcells pc where pc.parcel = p.id order by pc.y, pc.x limit 1) c1
                 from mp_parcels p where p.cho = any(cids) and p.ban = ban_ and (p.eda = eda_ or (eda_ = 0 and p.eda >= 0))
                order by (p.eda = eda_) desc, p.eda limit 5 loop
        if ('p' || r.id) = any(seen) then continue; end if;
        seen := seen || ('p' || r.id);
        out := out || jsonb_build_array(jsonb_build_object('k', 'addr', 'n', _mp_cho_full(r.cho) || _mp_ban(r.ban, r.eda), 's', coalesce(_mp_area_text(_mp_cho_area(r.cho)), '') || coalesce(' ' || r.bname, ''),
          'x', ((r.bb[0])[0] + (r.bb[1])[0]) / 10.0, 'y', ((r.bb[0])[1] + (r.bb[1])[1]) / 10.0, 'z', 26, 'b', r.bid, 'cx', r.c1[1], 'cy', r.c1[2], 'zip', _mp_cho_zip(r.cho), 'sro', _mp_area_ro(_mp_cho_area(r.cho))));
      end loop;
    end loop;
  end if;
  -- 3) 地名（ことばをふくむ。前に地名を書いたときは、その中）
  if rest <> '' then
    for r in select p.id, p.k, p.name, p.type, p.x, p.y, p.parent, p.ro, p.zip, p.name || coalesce(p.type, '') full_ from mp_places p
              where p.k in ('pref', 'muni', 'ward', 'island') and (p.name || coalesce(p.type, '')) like '%' || rest || '%'
                and (cardinality(sc) = 0 or p.parent = sc[cardinality(sc)])
              order by ((p.name || coalesce(p.type, '')) = rest or p.name = rest) desc, ((p.name || coalesce(p.type, '')) like rest || '%') desc, p.pop desc nulls last, p.id limit 8 loop
      if r.id = any(seen) then continue; end if;
      seen := seen || r.id;
      out := out || jsonb_build_array(jsonb_build_object('k', r.k, 'n', r.full_, 's', coalesce(_mp_area_text(r.parent), ''), 'x', r.x + 0.5, 'y', r.y + 0.5,
        'z', case r.k when 'pref' then 0.7 when 'muni' then 2.2 when 'ward' then 4 else 3 end, 'ro', r.ro, 'zip', r.zip, 'sro', _mp_area_ro(r.parent)));
    end loop;
  end if;
  -- 4) 町字（町・大字・字・丁目）
  if rest <> '' and char_length(rest) >= 1 then
    for r in select c.id, c.kind, c.x, c.y from mp_cho c
              where c.gone is null and c.kind in ('cho', 'oaza', 'aza') and c.name like '%' || regexp_replace(rest, '^(大字|字)', '') || '%'
                and exists (select 1 from mp_places a where a.id = _mp_cho_area(c.id))   -- 区域のない古い町字は出さない
                and (cardinality(sc) = 0 or _mp_cho_area(c.id) = sc[cardinality(sc)] or (select a.parent from mp_places a where a.id = _mp_cho_area(c.id)) = sc[cardinality(sc)])
              order by (c.name = rest) desc, (c.name like rest || '%') desc, (c.kind <> 'aza') desc, char_length(c.name), c.id limit 12 loop
      out := out || jsonb_build_array(jsonb_build_object('k', 'cho', 'n', _mp_cho_full(r.id), 's', _mp_cho_place(r.id, r.x, r.y), 'x', r.x + 0.5, 'y', r.y + 0.5, 'z', 12, 'zip', _mp_cho_zip(r.id), 'sro', _mp_area_ro(_mp_cho_area(r.id))));
    end loop;
    if rest ~ '丁目$' then
      for r in select c.id, c.x, c.y from mp_cho c join mp_cho p on p.id = c.parent
                where c.kind = 'chome' and c.gone is null and c.name = substring(rest from '([一二三四五六七八九十]+丁目)$')
                  and p.name like '%' || left(rest, char_length(rest) - char_length(c.name))
                  and exists (select 1 from mp_places a where a.id = p.parent)
                  and (cardinality(sc) = 0 or p.parent = sc[cardinality(sc)] or (select a.parent from mp_places a where a.id = p.parent) = sc[cardinality(sc)])
                limit 8 loop
        out := out || jsonb_build_array(jsonb_build_object('k', 'cho', 'n', _mp_cho_full(r.id), 's', _mp_cho_place(r.id, r.x, r.y), 'x', r.x + 0.5, 'y', r.y + 0.5, 'z', 16, 'zip', _mp_cho_zip(r.id), 'sro', _mp_area_ro(_mp_cho_area(r.id))));
      end loop;
    end if;
  end if;
  -- 5) 駅・空港・港・バス停（名前に q か rest をふくむ）
  for r in select s.id, s.kind, s.name, s.x, s.y from mp_stations s
            where s.name like '%' || q || '%' or (rest <> '' and rest <> q and s.name like '%' || rest || '%')
            order by (s.name = q or s.name = rest) desc, s.kind = 'bus', s.name, s.id limit 10 loop
    out := out || jsonb_build_array(jsonb_build_object('k', 'sta', 'sk', r.kind, 'n', r.name, 's', coalesce(_mp_addr(floor(r.x / 100.0)::int, floor(r.y / 100.0)::int, null, null) ->> 'text', ''),
      'x', r.x / 100.0, 'y', r.y / 100.0, 'z', case r.kind when 'air' then 6 when 'ship' then 10 else 16 end));
  end loop;
  -- 6) 建物の名前
  for r in select b.id, b.name, b.kind, b.cells[1] cx, b.cells[2] cy, p.bb from mp_blds b join mp_parcels p on p.id = b.parcel
            where b.name like '%' || q || '%' or (rest <> '' and rest <> q and char_length(rest) >= 2 and b.name like '%' || rest || '%')
            order by (b.name = q or b.name = rest) desc, (b.name like q || '%') desc, p.gov desc, b.floors desc, b.id limit 15 loop
    out := out || jsonb_build_array(jsonb_build_object('k', 'bld', 'n', r.name, 'bk', r.kind,
      's', coalesce(_mp_addr(_mp_t5(r.cx), _mp_t5(r.cy), r.cx, r.cy) ->> 'text', ''),
      'x', ((r.bb[0])[0] + (r.bb[1])[0]) / 10.0, 'y', ((r.bb[0])[1] + (r.bb[1])[1]) / 10.0, 'z', 24, 'b', r.id, 'cx', r.cx, 'cy', r.cy));
  end loop;
  return out;
end $$;

create or replace function public.mp_admin_place_at(p_x int, p_y int) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := _me(); c record; ar mp_places; mu mp_places; pr mp_places; ck text; a mp_cho; b mp_cho;
begin
  perform _mp_admin(u);
  select * into c from _mp_cell(p_x, p_y);
  if c.t is null then raise exception '地図の外です'; end if;
  select * into ar from mp_places where id = c.a;
  if ar.k = 'ward' then select * into mu from mp_places where id = ar.parent; else mu := ar; end if;
  select * into pr from mp_places where id = mu.parent;
  ck := _mp_cho_at(p_x, p_y);
  if ck is not null then
    select * into a from mp_cho where id = ck;
    if a.kind in ('chome', 'aza') then select * into b from mp_cho where id = a.parent; else b := a; a := null; end if;
  end if;
  return jsonb_build_object(
    'pref', case when pr.id is not null then jsonb_build_object('id', pr.id, 'name', pr.name, 'type', coalesce(nullif(pr.type, ''), '県'), 'gen', pr.extra ->> 'gen', 'yomi', pr.yomi, 'ro', pr.ro) end,
    'gun', case when coalesce(mu.extra ->> 'gun', '') <> '' and mu.type in ('町', '村') then jsonb_build_object('id', mu.extra ->> 'gid', 'name', mu.extra ->> 'gun', 'gen', mu.extra ->> 'gen_gun', 'yomi', mu.extra ->> 'gyomi', 'ro', _mp_ro_name(mu.extra ->> 'gyomi', '郡')) end,
    'muni', case when mu.id is not null then jsonb_build_object('id', mu.id, 'name', mu.name, 'type', mu.type, 'gen', mu.extra ->> 'gen', 'yomi', mu.yomi, 'ro', mu.ro, 'zip', mu.zip) end,
    'ward', case when ar.k = 'ward' then jsonb_build_object('id', ar.id, 'name', ar.name, 'gen', ar.extra ->> 'gen', 'yomi', ar.yomi, 'ro', ar.ro, 'zip', ar.zip) end,
    'cho', case when b.id is not null then jsonb_build_object('id', b.id, 'kind', b.kind, 'name', b.name,
              'subs', (select count(*) from mp_cho where parent = b.id and gone is null), 'zip', b.zip) end,
    'sub', case when a.id is not null then jsonb_build_object('id', a.id, 'kind', a.kind, 'name', a.name, 'num', a.num) end,
    -- 島（t54k2）：このマスをふくむ島（囲む四角の中で、いちばん近いもの）
    'isl', (select jsonb_build_object('id', i.id, 'name', i.name) from mp_places i where i.k = 'island'
              and p_x between (i.extra -> 'bb' ->> 0)::int and (i.extra -> 'bb' ->> 2)::int and p_y between (i.extra -> 'bb' ->> 1)::int and (i.extra -> 'bb' ->> 3)::int
              order by i.pt <-> point(p_x, p_y) limit 1),
    'cho_id', ck, 'text', _mp_addr(p_x, p_y, null, null) ->> 'text');
end $$;

create or replace function public.mp_admin_rename(p_kind text, p_id text, p_name text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := _me(); nm text := left(trim(coalesce(p_name, '')), 30);
begin
  perform _mp_admin(u);
  if nm = '' then raise exception '名前を入れてください'; end if;
  if p_kind = 'place' then update mp_places set yomi = case when name = nm then yomi end, name = nm where id = p_id;   -- 名前が変わったら 読みは消す（DB の更新114）   -- 県・市町村・区・川（「県」「市」「区」などはつけない）
  elsif p_kind = 'gun' then update mp_places set extra = case when extra ->> 'gun' = nm then extra else extra - 'gyomi' end || jsonb_build_object('gun', nm) where k = 'muni' and extra ->> 'gid' = p_id;
  elsif p_kind = 'cho' then update mp_cho set name = nm where id = p_id and gone is null;
  elsif p_kind = 'seg' then update mp_segs set name = nm where id = p_id::bigint;
  elsif p_kind = 'node' then update mp_nodes set name = nm where id = p_id::bigint;
  elsif p_kind = 'sta' then update mp_stations set name = nm where id = p_id::bigint;
  else raise exception '種類がちがいます'; end if;
  if not found then raise exception '見つかりません'; end if;
  perform _mp_chg(p_kind, null, 'set', null);
  return jsonb_build_object('ok', true);
end $$;

-- 地名のローマ字（都道府県・市区町村・区）：{id: ローマ字}。地図の設定で ローマ字を出すとき（DB の更新114）
create or replace function public.mp_place_ro() returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := _me_g();
begin
  perform _mp_ok(u);
  return (select coalesce(jsonb_object_agg(id, ro), '{}'::jsonb) from mp_places where k in ('pref', 'muni', 'ward') and ro is not null);
end $$;
revoke all on function public.mp_place_ro() from public, anon;
grant execute on function public.mp_place_ro() to authenticated;
-- 管理：地名・郡の読み（ひらがな。空なら消す。町を「ちょう」と読むときは「すずの ちょう」）（DB の更新114）
create or replace function public.mp_admin_yomi(p_kind text, p_id text, p_yomi text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := _me(); zy text; zr text;
begin
  perform _mp_admin(u);
  zy := translate(normalize(coalesce(p_yomi, ''), NFKC), 'ァアィイゥウェエォオカガキギクグケゲコゴサザシジスズセゼソゾタダチヂッツヅテデトドナニヌネノハバパヒビピフブプヘベペホボポマミムメモャヤュユョヨラリルレロヮワヰヱヲンヴ',
                                                       'ぁあぃいぅうぇえぉおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねのはばぱひびぴふぶぷへべぺほぼぽまみむめもゃやゅゆょよらりるれろゎわゐゑをんゔ');
  zy := nullif(btrim(regexp_replace(zy, '\s+', ' ', 'g')), '');
  if zy is not null and zy !~ '^[ぁ-ゖー]{1,30}( [ぁ-ゖ]{1,4})?$' then
    raise exception '読みは ひらがなで入れてください（町を「ちょう」・村を「そん」と読むときは「すずの ちょう」のように 空白のあとに）';
  end if;
  if p_kind = 'place' then
    update mp_places set yomi = zy where id = p_id and k in ('pref', 'muni', 'ward') returning ro into zr;
  elsif p_kind = 'gun' then
    update mp_places set extra = case when zy is null then extra - 'gyomi' else extra || jsonb_build_object('gyomi', zy) end where k = 'muni' and extra ->> 'gid' = p_id;
    zr := _mp_ro_name(zy, '郡');
  else raise exception '種類がちがいます'; end if;
  if not found then raise exception '見つかりません'; end if;
  perform _mp_chg('place', null, 'set', null);
  return jsonb_build_object('ok', true, 'yomi', zy, 'ro', zr);
end $$;
revoke all on function public.mp_admin_yomi(text, text, text) from public, anon;
grant execute on function public.mp_admin_yomi(text, text, text) to authenticated;
