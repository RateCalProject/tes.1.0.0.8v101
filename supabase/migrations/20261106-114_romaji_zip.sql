create or replace function public._mp_kana_ro(s text) returns text
language plpgsql immutable as $$
declare zs text := translate(coalesce(s, ''), 'ァアィイゥウェエォオカガキギクグケゲコゴサザシジスズセゼソゾタダチヂッツヅテデトドナニヌネノハバパヒビピフブプヘベペホボポマミムメモャヤュユョヨラリルレロヮワヰヱヲンヴ',
                                            'ぁあぃいぅうぇえぉおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねのはばぱひびぴふぶぷへべぺほぼぽまみむめもゃやゅゆょよらりるれろゎわゐゑをんゔ');
        zm jsonb := '{"あ":"a","い":"i","う":"u","え":"e","お":"o","か":"ka","き":"ki","く":"ku","け":"ke","こ":"ko","が":"ga","ぎ":"gi","ぐ":"gu","げ":"ge","ご":"go",
          "さ":"sa","し":"shi","す":"su","せ":"se","そ":"so","ざ":"za","じ":"ji","ず":"zu","ぜ":"ze","ぞ":"zo","た":"ta","ち":"chi","つ":"tsu","て":"te","と":"to",
          "だ":"da","ぢ":"ji","づ":"zu","で":"de","ど":"do","な":"na","に":"ni","ぬ":"nu","ね":"ne","の":"no","は":"ha","ひ":"hi","ふ":"fu","へ":"he","ほ":"ho",
          "ば":"ba","び":"bi","ぶ":"bu","べ":"be","ぼ":"bo","ぱ":"pa","ぴ":"pi","ぷ":"pu","ぺ":"pe","ぽ":"po","ま":"ma","み":"mi","む":"mu","め":"me","も":"mo",
          "や":"ya","ゆ":"yu","よ":"yo","ら":"ra","り":"ri","る":"ru","れ":"re","ろ":"ro","わ":"wa","ゐ":"i","ゑ":"e","を":"o","ゔ":"vu",
          "ぁ":"a","ぃ":"i","ぅ":"u","ぇ":"e","ぉ":"o","ゃ":"ya","ゅ":"yu","ょ":"yo","ゎ":"wa",
          "きゃ":"kya","きゅ":"kyu","きょ":"kyo","ぎゃ":"gya","ぎゅ":"gyu","ぎょ":"gyo","しゃ":"sha","しゅ":"shu","しょ":"sho","しぇ":"she",
          "じゃ":"ja","じゅ":"ju","じょ":"jo","じぇ":"je","ちゃ":"cha","ちゅ":"chu","ちょ":"cho","ちぇ":"che","ぢゃ":"ja","ぢゅ":"ju","ぢょ":"jo",
          "にゃ":"nya","にゅ":"nyu","にょ":"nyo","ひゃ":"hya","ひゅ":"hyu","ひょ":"hyo","びゃ":"bya","びゅ":"byu","びょ":"byo","ぴゃ":"pya","ぴゅ":"pyu","ぴょ":"pyo",
          "みゃ":"mya","みゅ":"myu","みょ":"myo","りゃ":"rya","りゅ":"ryu","りょ":"ryo","ふぁ":"fa","ふぃ":"fi","ふぇ":"fe","ふぉ":"fo","てぃ":"ti","でぃ":"di","うぃ":"wi","うぇ":"we","うぉ":"wo"}'::jsonb;
        zi int := 1; zn int; zc text; zx text; zr text; zq text; zo text := '';
begin
  zn := char_length(zs);
  while zi <= zn loop
    zc := substr(zs, zi, 1); zx := substr(zs, zi + 1, 1);
    if zc = 'っ' then                                        -- 小さい つ：つぎの子音を かさねる（ち → tch）
      zq := coalesce(zm ->> (zx || substr(zs, zi + 2, 1)), zm ->> zx, '');
      zo := zo || case when zq like 'ch%' then 't' when zq ~ '^[bcdfghjkmprstvwz]' then left(zq, 1) else '' end;
      zi := zi + 1; continue;
    end if;
    if zc = 'ん' then                                        -- ん：つぎが 母音・や行なら n'
      zq := coalesce(zm ->> zx, '');
      zo := zo || case when zq ~ '^[aiueoy]' then 'n''' else 'n' end;
      zi := zi + 1; continue;
    end if;
    if zc = 'ー' then                                        -- のばす音
      zo := regexp_replace(zo, '([aiueo])$', '') || coalesce(translate(substring(zo from '([aiueo])$'), 'aiueo', 'āīūēō'), '');
      zi := zi + 1; continue;
    end if;
    if zx <> '' and zm ? (zc || zx) then zr := zm ->> (zc || zx); zi := zi + 2;
